CREATE SEQUENCE SEQ_T_FINTECH_DESPESA START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_T_FINTECH_RECEITA START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_T_FINTECH_INVESTIMENTO START WITH 1 INCREMENT BY 1;

CREATE TABLE T_FINTECH_USUARIO (
  ID_USUARIO    NUMBER PRIMARY KEY,
  NM_COMPLETO   VARCHAR2(100) NOT NULL,
  NM_CPF        VARCHAR2(14)  NOT NULL,
  DT_NASCIMENTO DATE,
  DS_GENERO     VARCHAR2(20),
  NM_TELEFONE   VARCHAR2(20),
  DS_EMAIL      VARCHAR2(100) NOT NULL,
  DS_SENHA      VARCHAR2(100) NOT NULL,
);

CREATE TABLE T_FINTECH_DESPESA (
  ID_DESPESA     NUMBER PRIMARY KEY,
  ID_USUARIO     NUMBER NOT NULL REFERENCES T_FINTECH_USUARIO (ID_USUARIO),
  DS_GASTO       VARCHAR2(150),
  VL_GASTO       NUMBER(12,2),
  DT_VENCIMENTO  DATE,
  ST_PAGO        VARCHAR2(20)
);

CREATE TABLE T_FINTECH_RECEITA (
  ID_RECEITA     NUMBER PRIMARY KEY,
  ID_USUARIO     NUMBER NOT NULL REFERENCES T_FINTECH_USUARIO (ID_USUARIO),
  DS_RECEITA     VARCHAR2(150),
  VL_RECEITA     NUMBER(12,2),
  DT_RECEBIMENTO DATE
);

CREATE TABLE T_FINTECH_INVESTIMENTO (
  ID_INVESTIMENTO NUMBER PRIMARY KEY,
  ID_USUARIO      NUMBER NOT NULL REFERENCES T_FINTECH_USUARIO (ID_USUARIO),
  DS_INVESTIMENTO VARCHAR2(150),
  VL_INVESTIMENTO NUMBER(12,2),
  DT_APLICACAO    DATE
);

